const WARN = `<svg viewBox="0 0 24 24" fill="none"><path d="M12 3.5 22 20H2L12 3.5Z" stroke="currentColor" stroke-width="1.6" stroke-linejoin="round"/><path d="M12 10v4M12 17h.01" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"/></svg>`;

const CHAPTERS = {
  1: 'Danmarks historie', 2: 'Det danske demokrati', 3: 'Den danske økonomi',
  4: 'Danmark og omverdenen', 5: 'Dansk kulturliv', 6: 'Temaopslag',
};

const sitting = (tag) => {
  const [year, month] = tag.split('#')[0].split('-');
  return `${Number(month) > 8 ? 'vinter' : 'sommer'} ${year}`;
};

/**
 * Facts age. A question is only ever true as of the day it was set, so the
 * panel says when it was asked and warns where the world has since moved.
 * Current-affairs questions are dated by definition: in 2020 the answer to
 * "hvilket parti er i regering" was one thing, and Denmark had a Queen rather
 * than a King. Those are shown as history, never as today's answer.
 */
function dating(q) {
  const last = q.seen.map((s) => s.split('#')[0]).sort().at(-1);
  if (q.dated) {
    return `<div class="caution">${WARN}<span>${q.dated}</span></div>`;
  }
  if (q.section === 'aktuelt') {
    return `<div class="caution">${WARN}<span>
      Aktuelt spørgsmål fra <b>${sitting(last)}</b>. Svaret var rigtigt dengang,
      og er ikke nødvendigvis rigtigt i dag. På din prøve handler de fem aktuelle
      spørgsmål om året, du går op. Følg med i danske nyheder.
    </span></div>`;
  }
  return '';
}

function buildWhy(q, right) {
  const relic = RELICS[state.run.i % RELICS.length];
  const times = q.seen.length;
  const where = q.chapter
    ? `Kapitel ${q.chapter}, ${CHAPTERS[q.chapter]}${q.page ? `, side ${q.page}` : ''}.`
    : '';

  // Three tiers, in order of how much they teach. A written explanation first.
  // Failing that, the sentence from the læremateriale that states the answer,
  // quoted with its page. Restating the answer teaches nothing and is not an
  // option: the green highlight already said it.
  const body = q.explain
    ? `<p>${q.explain}</p>`
    : q.supports && q.passage
      ? `<blockquote>${q.passage}</blockquote>
         <p class="cite">Fra <b>Læremateriale til Indfødsretsprøven</b>, side ${q.page}.</p>`
      : `<p class="thin">Der er endnu ikke skrevet en forklaring til dette spørgsmål.
           Slå det efter i lærematerialet${q.page ? `, side ${q.page}` : ''}.</p>`;

  const why = document.createElement('div');
  why.className = 'why';
  why.innerHTML = `
    <p class="lbl">${relic.svg}${right ? relic.label : 'Det rigtige svar'}</p>
    ${body}
    ${dating(q)}
    <span class="src">
      ${times > 1
        ? `Stillet <b>${times} gange</b> siden 2020: ${q.seen.map(sitting).join(', ')}.`
        : `Stillet <b>${sitting(q.seen[0])}</b>.`}
      ${where}
      Officielt spørgsmål og retteark fra SIRI.
    </span>`;
  return why;
}

function next() {
  const run = state.run;
  if (run.i >= run.questions.length - 1) return finish();
  run.i++;
  renderQuestion();
}

/* ---------- result ---------- */
function finish() {
  const { mode, questions, marks } = state.run;
  const score = marks.filter(Boolean).length;
  const valuesIdx = questions.map((q, i) => (q.section === 'vaerdier' ? i : -1)).filter((i) => i >= 0);
  const valuesScore = valuesIdx.filter((i) => marks[i]).length;

  let passed = null;
  let gate = '';
  if (mode.exam) {
    const okTotal = score >= RULES.pass;
    const okValues = valuesScore >= RULES.valuesPass;
    passed = okTotal && okValues;
    gate = `<div class="gate ${okValues ? 'ok' : 'no'}">
      Værdispørgsmål: <b>${valuesScore} af ${RULES.values}</b> rigtige.
      ${okValues
        ? 'Kravet om mindst 4 er opfyldt.'
        : 'Kravet er mindst 4. Uden det dumper du prøven, uanset din samlede score.'}
    </div>`;
    if (okTotal && !okValues) {
      gate += `<p class="note">Du havde nok rigtige i alt, men værdikravet er en selvstændig hurdle.
        Det er præcis dér, folk falder.</p>`;
    }
  } else if (mode.gate) {
    passed = score >= mode.gate.need;
  } else if (mode.hall) {
    // Decided here, with the other verdicts, so the label below sees it.
    passed = score / questions.length >= HALL_PASS;
  }

  const label = mode.exam
    ? (passed ? 'Bestået' : 'Ikke bestået')
    : (passed === null ? 'Gennemført' : passed ? 'Bestået' : 'Ikke bestået');

  state.best[mode.id] = Math.max(state.best[mode.id] ?? 0, score);
  // Clearing a hall opens the next one, and only ever forwards.
  if (mode.hall && passed) {
    state.cleared = Math.max(state.cleared ?? 0, mode.index + 1);
  }
  save();
  if (passed !== false) sfx.done();

  $('resultCard').innerHTML = `
    <p class="lead">${mode.da}</p>
    <div class="score ${passed === false ? 'fail' : 'pass'}">${score} / ${questions.length}</div>
    <p class="verdict">${label}</p>
    ${gate}
    ${mode.hall
      ? `<p class="note">${passed
          ? 'Hallen er ryddet. Den næste har åbnet sig.'
          : `Du skal have ${Math.ceil(questions.length * HALL_PASS)} af ${questions.length} for at rydde hallen. Spørgsmålene blandes hver gang.`}</p>`
      : mode.exam
      ? `<p class="note">Til den rigtige prøve skal du have ${RULES.pass} af ${RULES.total} rigtige.</p>`
      : `<p class="note">${score === questions.length
          ? 'Fejlfrit. Tag Altinget, når du er klar til hele prøven.'
          : 'Gennemgå de forkerte, og tag den igen. Spørgsmålene blandes hver gang.'}</p>`}
    <div class="actions">
      <button class="btn primary" id="againBtn" type="button">Prøv igen</button>
      <button class="btn ghost" id="backPathBtn" type="button">Tilbage til vejen</button>
    </div>`;

  $('hudMeta').textContent = '';
  go('viewResult', sceneFor(mode));
  $('againBtn').onclick = () => start(mode.id, mode);
  $('backPathBtn').onclick = () => { renderPath(); go('viewPath', 'path'); };
  state.run = null;
}

/* ============================================================
   Boot
   ============================================================ */
async function main() {
  scenes.mount($('scene'));
  load();

  const [questions, explanations] = await Promise.all([
    fetch('./data/questions.jsonl').then((r) => r.text()),
    fetch('./data/explanations.jsonl').then((r) => (r.ok ? r.text() : '')).catch(() => ''),
  ]);

  const why = new Map(
    explanations.split('\n').filter(Boolean)
      .map((l) => JSON.parse(l)).map((e) => [e.id, e]));

  state.bank = questions.split('\n').filter(Boolean).map((line) => {
    const q = JSON.parse(line);
    const extra = why.get(q.id);
    // Hand-written fields win over generated ones (a human-checked page
    // citation beats the located guess), but never the identity.
    return extra ? { ...q, ...extra, id: q.id } : q;
  });

  renderShore();
  if (state.guide) choose(state.guide);
  $('soundToggle').textContent = state.sound ? 'Lyd til' : 'Lyd fra';
  $('soundToggle').setAttribute('aria-pressed', String(state.sound));

  scenes.show('shore');
  $('boot').hidden = true;
}

