function start(modeId, override) {
  const mode = override ?? MODES.find((m) => m.id === modeId);
  const seed = Date.now();
  const questions = mode.build().map((q) => present(q, seed));
  if (!questions.length) return;

  state.run = {
    mode, seed, questions, i: 0, marks: Array(questions.length).fill(null),
    deadline: mode.exam ? Date.now() + RULES.minutes * 60000 : null,
  };
  $('hudTitle').textContent = mode.da;
  $('hudBackLabel').textContent = 'Forlad';
  go('viewQuiz', sceneFor(mode));
  renderQuestion();
  if (state.run.deadline) tick();
}

function tick() {
  const run = state.run;
  if (!run?.deadline) return;
  const left = run.deadline - Date.now();
  if (left <= 0) return finish();
  $('hudMeta').textContent =
    `${String(Math.floor(left / 60000)).padStart(2, '0')}:${String(Math.floor(left / 1000) % 60).padStart(2, '0')}`;
  setTimeout(tick, 1000);
}

function renderFleet() {
  const { marks, i } = state.run;
  $('fleet').innerHTML = marks.map((m, n) =>
    `<i class="${m === true ? 'hit' : m === false ? 'miss' : n === i ? 'now' : ''}">${SHIP}</i>`).join('');
}

function renderQuestion() {
  const run = state.run;
  const q = run.questions[run.i];
  const letters = ['A', 'B', 'C'];

  if (!run.deadline) $('hudMeta').textContent = `${run.i + 1} / ${run.questions.length}`;
  renderFleet();
  $('quizNext').disabled = true;
  $('quizNextLabel').textContent =
    run.i === run.questions.length - 1 ? 'Afslut' : 'Næste';

  $('quizCard').innerHTML = `
    <p class="q">${q.q}</p>
    ${q.options.map((o, n) => `
      <button class="opt" type="button" data-n="${n}" style="--d:${n * 0.05}s">
        <em>${letters[n]}</em><span>${o}</span>
      </button>`).join('')}`;

  $('quizCard').querySelectorAll('.opt').forEach((btn) =>
    btn.addEventListener('click', () => answer(Number(btn.dataset.n)), { once: true }));
}

function answer(chosen) {
  const run = state.run;
  const q = run.questions[run.i];
  const right = chosen === q.answerAt;
  run.marks[run.i] = right;

  const opts = [...$('quizCard').querySelectorAll('.opt')];
  opts.forEach((b) => { b.disabled = true; });
  opts[q.answerAt].classList.add('hit');
  if (!right) opts[chosen].classList.add('miss');
  right ? sfx.hit() : sfx.miss();
  renderFleet();

  $('quizCard').append(buildWhy(q, right));
  $('quizNext').disabled = false;
}

