/* ============================================================
   Persistence
   ============================================================ */
function load() {
  try {
    Object.assign(state, JSON.parse(localStorage.getItem(SAVE) ?? '{}'));
  } catch { /* corrupt or blocked storage is not worth a crash */ }
}
function save() {
  try {
    localStorage.setItem(SAVE, JSON.stringify({
      guide: state.guide, best: state.best, sound: state.sound, cleared: state.cleared,
    }));
  } catch { /* private mode: run without persistence rather than fail */ }
}

/* ============================================================
   Deterministic shuffling

   Option order is randomised so nobody learns "the answer is C".
   That matters here: across the 13 published papers C is correct
   39.3% of the time on three-option questions where chance says
   33.3%, so fixed order teaches a position habit instead of the
   content. The shuffle is seeded so a given run is reproducible,
   which is what later makes shared ghost battles fair.
   ============================================================ */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const hash = (s) => [...s].reduce((h, c) => Math.imul(h ^ c.charCodeAt(0), 16777619), 2166136261);

function shuffle(list, rand) {
  const out = [...list];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function present(entry, seed) {
  // ponytail: Ja/Nej keeps its natural order. With two options, knowing "Ja"
  // already is knowing the content, so shuffling only makes the UI feel wrong.
  const yesNo = entry.options.length === 2 && entry.options.every((o) => /^(Ja|Nej)$/.test(o));
  const options = yesNo ? entry.options : shuffle(entry.options, rng(hash(entry.id + seed)));
  return { ...entry, options, answerAt: options.indexOf(entry.answer) };
}

/* ============================================================
   Sound: synthesised, no audio files ship with this
   ============================================================ */
let audio = null;
function tone(freq, dur = 0.12, type = 'sine', gain = 0.05) {
  if (!state.sound) return;
  audio ??= new (window.AudioContext ?? window.webkitAudioContext)();
  const osc = audio.createOscillator();
  const amp = audio.createGain();
  osc.type = type;
  osc.frequency.value = freq;
  amp.gain.setValueAtTime(gain, audio.currentTime);
  amp.gain.exponentialRampToValueAtTime(0.0001, audio.currentTime + dur);
  osc.connect(amp).connect(audio.destination);
  osc.start();
  osc.stop(audio.currentTime + dur);
}
const sfx = {
  hit: () => { tone(660, 0.1); setTimeout(() => tone(990, 0.16), 70); },
  miss: () => tone(150, 0.22, 'triangle', 0.04),
  done: () => [523, 659, 784].forEach((f, i) => setTimeout(() => tone(f, 0.3), i * 110)),
};

